import { writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { loadContent } from './content.ts'

const source = resolve(import.meta.dir, '..', process.env['SOURCE_DIR'] ?? '../source')
const { manifest } = await loadContent(source)
const { site } = manifest

const table = [
  '| Script | Version | What it does | Links |',
  '| --- | --- | --- | --- |',
  ...manifest.scripts.map((script) => `| **${script.name}** | ${script.version} | ${script.description} | [Install](${script.installUrl}) · [Docs](${site.url}${script.slug}/) |`)
]

const sections = manifest.scripts.flatMap((script) => {
  const guides = script.pages.filter((page) => page.kind === 'guide')
  return [
    `### ${script.name}`,
    '',
    script.description,
    '',
    `[Install](${script.installUrl}) · [Documentation](${site.url}${script.slug}/) · [Changelog](${site.url}${script.slug}/changelog/) · [Source](${script.folderUrl})`,
    '',
    ...(guides.length ? ['Guides:', '', ...guides.map((page) => `- [${page.title}](${site.url}${page.path}): ${page.description}`), ''] : [])
  ]
})

const readme = `<!-- Generated by scripts/readme.ts on the website branch from each script's Markdown files. Edit those, not this file. -->

# Userscripts

Small, focused userscripts by [Nolly](https://github.com/thenolle). Each lives in its own folder with its own source, guides, changelog and version.

**[Read the documentation](${site.url})**

## Scripts

${table.join('\n')}

## Installing

1. Install a userscript manager such as [Violentmonkey](https://violentmonkey.github.io/) or [Tampermonkey](https://www.tampermonkey.net/).
2. Open a script's **Install** link and confirm.
3. Updates arrive automatically from this repository.

## What is inside

${sections.join('\n')}
## How this repository works

- One folder per userscript, each a TypeScript project built with [Bun](https://bun.sh).
- A version bump on \`master\` publishes a release, a minified build and an update feed on the \`dist\` branch.
- The documentation site lives on the \`website\` branch and rebuilds from these folders on every change. It is built with [Gambrel](https://github.com/thenolle/gambrel).

## Contributing and support

Read [CONTRIBUTING.md](CONTRIBUTING.md), open an [issue](https://github.com/${site.repo}/issues), or [sponsor the work](${site.sponsor}). Security reports go through a [private advisory](https://github.com/${site.repo}/security/advisories/new).

## License

[PolyForm Strict License 1.0.0](LICENSE): free for noncommercial use, with no distribution and no modified versions.
`

await writeFile(join(source, 'README.md'), readme, 'utf8')
console.log(`README.md written with ${manifest.scripts.length} scripts`)